import { ArrowRight, FileText, Plus } from 'lucide-react'
import { Link } from 'react-router-dom'
import { PageHeader } from '@/components/shared/PageHeader'
import { EmptyState, LoadingState } from '@/components/shared/states'
import { EvidenceBadge } from '@/components/shared/evidence-badge'
import { Badge } from '@/components/ui/badge'
import { Button } from '@/components/ui/button'
import { Card, CardContent } from '@/components/ui/card'
import { useAnalyses, useReport } from '@/api/hooks'
import { formatRelativeTime } from '@/lib/utils'

export function ReportsPage() {
  const { data: report, isLoading } = useReport('AST-2026-001')
  const { data: analyses } = useAnalyses()
  const completed = (analyses ?? []).filter((a) => a.status === 'Completed' && a.id !== 'AST-2026-001')

  return (
    <div className="animate-fade-up">
      <PageHeader
        eyebrow="Reports"
        title="Research reports"
        subtitle="Citation-backed, explainable assessments generated by the Report Generation Agent."
        actions={<Button asChild><Link to="/analyses/new"><Plus /> New Analysis</Link></Button>}
      />

      {isLoading ? (
        <LoadingState rows={3} label="Loading reports" />
      ) : !report ? (
        <EmptyState title="No reports yet" description="Complete an analysis to generate your first research report." />
      ) : (
        <div className="space-y-4">
          <Card className="overflow-hidden border-primary-200 bg-gradient-to-r from-primary-50/70 to-surface transition-all duration-300 hover:shadow-lift">
            <CardContent className="flex flex-col gap-5 p-6 sm:flex-row sm:items-center">
              <span className="flex size-12 shrink-0 items-center justify-center rounded-xl bg-gradient-to-br from-primary-600 to-accent shadow-sm">
                <FileText className="size-6 text-white" aria-hidden />
              </span>
              <div className="min-w-0 flex-1">
                <div className="flex flex-wrap items-center gap-2">
                  <Badge variant="default">Latest</Badge>
                  <EvidenceBadge band="Strong" score={87} />
                </div>
                <h2 className="mt-1.5 truncate text-lg font-bold tracking-tight">Montelukast → COPD</h2>
                <p className="mt-0.5 text-sm text-mutedfg">
                  13 sections · 24 references · generated {formatRelativeTime(report.generatedAt)}
                </p>
              </div>
              <Button asChild size="lg">
                <Link to={`/reports/${report.id}`}>
                  Open report <ArrowRight />
                </Link>
              </Button>
            </CardContent>
          </Card>

          {completed.map((a) => (
            <Card key={a.id} className="opacity-90 transition-all duration-300 hover:translate-x-0.5 hover:border-primary-200">
              <CardContent className="flex items-center gap-4 p-5">
                <span className="flex size-10 shrink-0 items-center justify-center rounded-xl bg-slate-100 ring-1 ring-line">
                  <FileText className="size-4.5 text-slate-500" aria-hidden />
                </span>
                <div className="min-w-0 flex-1">
                  <h3 className="truncate font-semibold">{a.drugName} → {a.diseaseName}</h3>
                  <p className="text-xs text-mutedfg">{a.id} · updated {formatRelativeTime(a.updatedAt)}</p>
                </div>
                <Badge variant={a.evidenceBand === 'Strong' ? 'emerald' : a.evidenceBand === 'Moderate' ? 'amber' : 'neutral'}>
                  {a.evidenceBand ?? 'Pending'} · {a.confidence ?? '—'}
                </Badge>
              </CardContent>
            </Card>
          ))}
        </div>
      )}
    </div>
  )
}
